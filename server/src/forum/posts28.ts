/** Writes the threads not yet on the forum; returns how many were written. */
export function postThreads28(store: ForumStore, now: number): number {
  let n = 0;
  store.tx(() => {
    THREADS_28.forEach((t, i) => {
      const s = store.sectionBySlug(t.section);
      if (!s) return;
      if (store.sectionTopics(s.id, true, 0, 500).some((x) => x.title === t.title)) return;
      const at = now + i * 1000;
      const tid = store.addTopic(s.id, SYSTEM_ID, t.title, at);
      const p = store.addPost(tid, SYSTEM_ID, t.body, null, at);
      store.touchTopic(tid, p.id, SYSTEM_ID, at, true);
      store.setTopic(tid, { official: 1, ...(t.pinned ? { pinned: 1 } : {}) });
      store.setPost(p.id, { official: 1 });
      store.index('t', tid, t.title);
      store.index('p', p.id, plainText(t.body));
      store.bump(SYSTEM_ID, 'posts', 1);
      store.bump(SYSTEM_ID, 'topics', 1);
      store.bump(SYSTEM_ID, 'official', 1);
      n++;
    });
  });
  return n;
}

