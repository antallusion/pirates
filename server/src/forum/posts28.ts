/** Writes the answers not yet on the forum; returns how many were written. */
export function postReplies29(store: ForumStore, now: number): number {
  let n = 0;
  store.tx(() => {
    REPLIES_29.forEach((r, i) => {
      // our own threads by their title; a player's thread by the post answered in it
      const s = THREADS_28.find((t) => t.title === r.topic);
      const sec = s && store.sectionBySlug(s.section);
      const asked = r.to !== null ? store.post(r.to) : undefined;
      const topic = sec ? store.sectionTopics(sec.id, true, 0, 500).find((x) => x.title === r.topic) : asked && store.topic(asked.topic_id)?.title === r.topic ? store.topic(asked.topic_id) : undefined;
      if (!topic) return;
      const mine = store.topicPosts(topic.id, 0, 1000).filter((p) => p.author_id === SYSTEM_ID);
      if (mine.some((p) => p.body_md === r.body)) return;
      // (the owner changed the facts after the answer went up: the answer to that post is rewritten, not doubled)
      const was = r.to !== null ? mine.find((p) => p.reply_to === r.to) : undefined;
      if (was) {
        store.editPost(was.id, r.body, SYSTEM_ID, now);
        store.index('p', was.id, plainText(r.body));
        n++;
        return;
      }
      const to = r.to !== null ? store.post(r.to) : undefined;
      const replyTo = to && to.topic_id === topic.id ? to.id : null;
      const at = now + i * 1000;
      const p = store.addPost(topic.id, SYSTEM_ID, r.body, replyTo, at);
      store.touchTopic(topic.id, p.id, SYSTEM_ID, at, false);
      store.setPost(p.id, { official: 1 });
      store.index('p', p.id, plainText(r.body));
      store.bump(SYSTEM_ID, 'posts', 1);
      store.bump(SYSTEM_ID, 'official', 1);
      if (to && replyTo !== null && to.author_id !== SYSTEM_ID) store.notify(to.author_id, 'reply', SYSTEM_ID, topic.id, p.id, at);
      n++;
    });
  });
  return n;
}

/** An official topic from the administration (the game's own news: the PvP season's results, pvprank.ts) in a section,
 *  written once by its title. True: written. */
export function postOfficial(store: ForumStore, section: string, title: string, body: string, now: number): boolean {
  const s = store.sectionBySlug(section);
  if (!s || store.sectionTopics(s.id, true, 0, 500).some((x) => x.title === title)) return false;
  store.tx(() => {
    const tid = store.addTopic(s.id, SYSTEM_ID, title, now);
    const p = store.addPost(tid, SYSTEM_ID, body, null, now);
    store.touchTopic(tid, p.id, SYSTEM_ID, now, true);
    store.setTopic(tid, { official: 1 });
    store.setPost(p.id, { official: 1 });
    store.index('t', tid, title);
    store.index('p', p.id, plainText(body));
    store.bump(SYSTEM_ID, 'posts', 1);
    store.bump(SYSTEM_ID, 'topics', 1);
    store.bump(SYSTEM_ID, 'official', 1);
  });
  return true;
}
