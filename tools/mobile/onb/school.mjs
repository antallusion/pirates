// VK 4.2.4 proof (2026-11-05): the sea school walked by hand — each lesson's screen, its finger, what it reveals.
import { browser, page, login, sleep } from '../m0/lib.mjs';
const OUT = process.env.OUT ?? 'assets/raw/audit/onb';
const [W, H] = (process.env.SIZE ?? '812x375').split('x').map(Number);
const tag = `${W}x${H}`;
const b = await browser();
const p = await page(b, [W, H]);
await login(p, { port: Number(process.env.GPORT) });
await sleep(2500);
const ob = () => p.evaluate(() => { const o = globalThis.gravetide.state.onboarding; return o ? `${o.stage}/${o.lesson ?? '-'} ${o.index + 1}/${o.of} hud=${(o.hud ?? []).join(',')}` : 'none'; });
const shot = async (n) => { await p.screenshot({ path: `${OUT}/W-${tag}-${n}.png` }); console.log(n, await ob(), '| watch:', await p.evaluate(() => document.getElementById('hud-watch')?.innerText.replace(/\s+/g, ' ').slice(0, 160))); };
const waitLesson = async (want, ms = 30000) => { const t0 = Date.now(); while (Date.now() - t0 < ms) { const o = await p.evaluate(() => globalThis.gravetide.state.onboarding); if ((o?.lesson ?? o?.stage) === want || o?.stage === want) return true; await sleep(500); } return false; };
await shot('1-cast');
await p.evaluate(() => document.getElementById('tc-cast')?.click());
await waitLesson('sails');
await sleep(1500);
await shot('2-sails');
const touch = W < 1000;
for (let i = 0; i < 3; i++) { if (touch) await p.evaluate(() => document.querySelector('#tc-sail [data-sail="1"]')?.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true }))); else { await p.keyboard.down('w'); await sleep(150); await p.keyboard.up('w'); } await sleep(600); }
console.log('sails ok', await waitLesson('helm', 8000));
await sleep(1000);
await shot('3-helm');
await p.keyboard.down('d'); await sleep(5000); await p.keyboard.up('d');
console.log('helm ok', await waitLesson('dash', 15000));
await sleep(1000);
await shot('4-dash');
await p.keyboard.press('Shift');
console.log('dash ok', await waitLesson('course', 8000));
await sleep(1500);
await shot('5-course');
const g = await p.evaluate(() => globalThis.gravetide.state.onboarding?.goal);
console.log('goal', JSON.stringify(g));
if (g) await p.evaluate(([x, y]) => globalThis.gravetide.chart.onAutosail({ x, y }), [g.x, g.y]);
console.log('course ok', await waitLesson('isle', 10000));
await sleep(1500);
await shot('6-isle');
console.log('isle ok', await waitLesson('attack', 120000));
await sleep(2500);
await shot('7-attack');
console.log('errors', p.errors.slice(0, 5));
await b.close();
